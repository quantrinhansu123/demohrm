-- Cấu hình hoa hồng dự kiến theo công ty. Chạy trong schema trangway.
create table if not exists trangway.commission_entries (
  id            bigint generated by default as identity primary key,
  company_name  varchar(150) not null,
  unit_price    numeric(14,2) not null,
  period_code   varchar(30) not null,
  created_by    bigint references trangway.staff(id) on delete set null,
  created_at    timestamptz not null default now(),
  updated_at    timestamptz not null default now(),
  constraint commission_entries_unit_price_chk check (unit_price >= 0)
);

alter table trangway.commission_entries disable row level security;

grant select, insert, update, delete on trangway.commission_entries
  to anon, authenticated, service_role;
grant usage, select on sequence trangway.commission_entries_id_seq
  to anon, authenticated, service_role;

create unique index if not exists commission_entries_period_company_uidx
  on trangway.commission_entries (period_code, lower(company_name));

create index if not exists idx_commission_entries_period
  on trangway.commission_entries (period_code);
