-- Sổ chi hàng ngày. Chạy trong schema trangway.
-- Nên chạy fn_pay_advance.sql ngay sau file này (cùng đợt deploy).
create table if not exists trangway.cashbook_entries (
  id            bigint generated by default as identity primary key,
  entry_date    date not null,
  content       text not null,
  full_name     varchar(150),
  company_name  varchar(150),
  amount        numeric(14,2) not null,
  note          text,
  group_code    varchar(20) not null default 'office',
  group_name    varchar(100),
  source_type   varchar(20),
  source_id     bigint,
  created_at    timestamptz not null default now(),
  updated_at    timestamptz not null default now()
);

alter table trangway.cashbook_entries
  add column if not exists group_name varchar(100);

alter table trangway.cashbook_entries
  add column if not exists source_type varchar(20);

alter table trangway.cashbook_entries
  add column if not exists source_id bigint;

alter table trangway.cashbook_entries
  alter column group_code set default 'office';

-- Map legacy categories -> weekly_wage / office. Keep group_name for old "other" detail.
update trangway.cashbook_entries
   set group_code = case
     when group_code in ('advance', 'weekly_wage') then 'weekly_wage'
     else 'office'
   end
 where group_code not in ('weekly_wage', 'office');

-- Backfill advance provenance when advances table already exists.
do $$
begin
  if to_regclass('trangway.advances') is null then
    return;
  end if;
  update trangway.cashbook_entries ce
     set source_type = 'advance',
         source_id = a.id
    from trangway.advances a
   where a.cashbook_entry_id = ce.id
     and (ce.source_type is distinct from 'advance' or ce.source_id is distinct from a.id);
end $$;

alter table trangway.cashbook_entries
  drop constraint if exists cashbook_entries_group_code_check;
alter table trangway.cashbook_entries
  add constraint cashbook_entries_group_code_check
  check (group_code in ('weekly_wage', 'office'));

alter table trangway.cashbook_entries
  drop constraint if exists cashbook_entries_source_type_check;
alter table trangway.cashbook_entries
  add constraint cashbook_entries_source_type_check
  check (source_type is null or source_type in ('advance'));

alter table trangway.cashbook_entries disable row level security;

grant select, insert, update, delete on trangway.cashbook_entries
  to anon, authenticated, service_role;
grant usage, select on sequence trangway.cashbook_entries_id_seq
  to anon, authenticated, service_role;

create index if not exists idx_cashbook_entry_date
  on trangway.cashbook_entries (entry_date);

create index if not exists idx_cashbook_source
  on trangway.cashbook_entries (source_type, source_id)
  where source_type is not null;
