-- Phiếu tạm ứng. Chạy trong schema trangway.
create table if not exists trangway.advances (
  id                        bigint generated by default as identity primary key,
  code                      varchar(30) not null unique,
  subject_type              varchar(10) not null,
  worker_id                 bigint references trangway.workers(id),
  staff_id                  bigint references trangway.staff(id),
  amount                    numeric(14,2) not null,
  reason                    varchar(300) not null,
  status                    varchar(20) not null default 'requested',
  advance_date              date not null,
  advance_time              time not null,
  requested_by              bigint references trangway.staff(id),
  approved_by               bigint references trangway.staff(id),
  approved_at               timestamptz,
  paid_at                   timestamptz,
  settled_at                timestamptz,
  settled_amount            numeric(14,2),
  evidence_path             text,
  note                      text,
  cashbook_entry_id         bigint unique references trangway.cashbook_entries(id),
  legacy_salary_advance_id  bigint unique,
  created_at                timestamptz not null default now(),
  updated_at                timestamptz not null default now(),
  constraint advances_amount_chk check (amount > 0),
  constraint advances_status_chk check (
    status in ('requested', 'approved', 'paid', 'settled', 'rejected', 'cancelled')
  ),
  constraint advances_subject_chk check (
    (subject_type = 'worker' and worker_id is not null and staff_id is null)
    or
    (subject_type = 'staff' and staff_id is not null and worker_id is null)
  )
);

alter table trangway.advances disable row level security;

grant select, insert, update, delete on trangway.advances
  to anon, authenticated, service_role;
grant usage, select on sequence trangway.advances_id_seq
  to anon, authenticated, service_role;

create index if not exists idx_advances_date
  on trangway.advances (advance_date, advance_time);

create index if not exists idx_advances_status_date
  on trangway.advances (status, advance_date);

create index if not exists idx_advances_worker_date
  on trangway.advances (worker_id, advance_date);

create index if not exists idx_advances_staff_date
  on trangway.advances (staff_id, advance_date);
