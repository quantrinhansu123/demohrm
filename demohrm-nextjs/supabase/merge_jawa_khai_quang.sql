-- (và mọi bản trùng exact của tên Thời Vụ / bản thừa của tên keep).
-- Dùng chung bảng log + fn_rollback_company_merge (từ merge_duplicate_companies.sql).
--
-- 1) Preview (chạy riêng):
--    xem block PREVIEW bên dưới (comment).
-- 2) Chạy toàn bộ file này.
-- 3) Rollback: select trangway.fn_rollback_company_merge(<batch_id>);
-- =============================================================================

-- Đảm bảo bảng log đã có (no-op nếu đã chạy merge trước).
create table if not exists trangway.company_merge_batches (
  id             bigint generated by default as identity primary key,
  note           text not null default 'merge_duplicate_companies',
  created_at     timestamptz not null default now(),
  rolled_back    boolean not null default false,
  rolled_back_at timestamptz
);
create table if not exists trangway.company_merge_group_log (
  id            bigint generated by default as identity primary key,
  batch_id      bigint not null references trangway.company_merge_batches(id) on delete cascade,
  group_key     text not null,
  keep_id       bigint not null,
  keep_snapshot jsonb not null,
  drop_ids      bigint[] not null,
  created_at    timestamptz not null default now()
);
create table if not exists trangway.company_merge_deleted_companies (
  id            bigint generated by default as identity primary key,
  batch_id      bigint not null references trangway.company_merge_batches(id) on delete cascade,
  group_key     text not null,
  company_id    bigint not null,
  company_row   jsonb not null,
  created_at    timestamptz not null default now()
);
create table if not exists trangway.company_merge_row_log (
  id            bigint generated by default as identity primary key,
  batch_id      bigint not null references trangway.company_merge_batches(id) on delete cascade,
  group_key     text not null,
  table_name    text not null,
  row_pk        bigint not null,
  column_name   text not null,
  old_value     text,
  new_value     text,
  action        text not null check (action in ('update', 'delete')),
  deleted_row   jsonb,
  created_at    timestamptz not null default now()
);

-- PREVIEW:
-- select c.id, c.code, c.short_name,
--        case
--          when lower(trim(c.short_name)) = 'jawa - kcn khai quang' then 'KEEP_CANDIDATE'
--          when lower(trim(c.short_name)) = 'jawa - kcn khai quang - thời vụ' then 'DROP'
--          else 'OTHER'
--        end as action,
--        (select count(*) from trangway.orders o where o.company_id = c.id) as orders_cnt,
--        (select count(*) from trangway.workers w where w.current_company_id = c.id) as workers_cnt
--   from trangway.companies c
--  where lower(trim(c.short_name)) in (
--          'jawa - kcn khai quang',
--          'jawa - kcn khai quang - thời vụ'
--        )
--  order by c.short_name, c.id;

do $$
declare
  v_batch_id bigint;
  v_group_key text := 'jawa - kcn khai quang (+ thời vụ)';
  v_keep_id bigint;
  v_keep_short text;
  v_keep_row jsonb;
  v_drop_ids bigint[];
  v_drop_id bigint;
  v_drop_row record;
  v_drop_shorts text[];
  r record;
begin
  if to_regprocedure('trangway.fn_rollback_company_merge(bigint)') is null then
    raise exception 'Chưa có fn_rollback_company_merge. Chạy merge_duplicate_companies.sql trước (hoặc tạo hàm rollback).';
  end if;

  -- Giữ đúng tên "Jawa - KCN Khai quang"; nếu nhiều bản cùng tên → MAX(id).
  select max(c.id)
    into v_keep_id
    from trangway.companies c
   where lower(trim(c.short_name)) = 'jawa - kcn khai quang';

  if v_keep_id is null then
    raise exception 'Không tìm thấy công ty keep: Jawa - KCN Khai quang';
  end if;

  -- DROP: mọi "… - Thời Vụ" + bản "Jawa - KCN Khai quang" thừa (khác keep_id).
  select coalesce(array_agg(c.id order by c.id), '{}'::bigint[])
    into v_drop_ids
    from trangway.companies c
   where c.id <> v_keep_id
     and lower(trim(c.short_name)) in (
           'jawa - kcn khai quang',
           'jawa - kcn khai quang - thời vụ'
         );

  if coalesce(cardinality(v_drop_ids), 0) = 0 then
    raise notice 'Không còn bản trùng Jawa để gộp (keep_id=%)', v_keep_id;
    return;
  end if;

  select to_jsonb(c), c.short_name
    into v_keep_row, v_keep_short
    from trangway.companies c
   where c.id = v_keep_id;

  select coalesce(array_agg(distinct c.short_name), '{}'::text[])
    into v_drop_shorts
    from trangway.companies c
   where c.id = any (v_drop_ids);

  insert into trangway.company_merge_batches (note)
  values ('merge_jawa_khai_quang keep=' || v_keep_short || ' ' || to_char(now(), 'YYYY-MM-DD HH24:MI:SS'))
  returning id into v_batch_id;

  insert into trangway.company_merge_group_log (batch_id, group_key, keep_id, keep_snapshot, drop_ids)
  values (v_batch_id, v_group_key, v_keep_id, v_keep_row, v_drop_ids);

  raise notice 'JAWA merge batch_id=% keep=% (%) drop=%', v_batch_id, v_keep_id, v_keep_short, v_drop_ids;

  -- orders
  for r in
    select o.id, o.company_id from trangway.orders o where o.company_id = any (v_drop_ids)
  loop
    insert into trangway.company_merge_row_log
      (batch_id, group_key, table_name, row_pk, column_name, old_value, new_value, action)
    values (v_batch_id, v_group_key, 'orders', r.id, 'company_id', r.company_id::text, v_keep_id::text, 'update');
    update trangway.orders set company_id = v_keep_id where id = r.id;
  end loop;

  -- workers
  for r in
    select w.id, w.current_company_id from trangway.workers w where w.current_company_id = any (v_drop_ids)
  loop
    insert into trangway.company_merge_row_log
      (batch_id, group_key, table_name, row_pk, column_name, old_value, new_value, action)
    values (v_batch_id, v_group_key, 'workers', r.id, 'current_company_id', r.current_company_id::text, v_keep_id::text, 'update');
    update trangway.workers set current_company_id = v_keep_id where id = r.id;
  end loop;

  -- work_sites
  if to_regclass('trangway.work_sites') is not null then
    for r in
      select s.id, s.company_id from trangway.work_sites s where s.company_id = any (v_drop_ids)
    loop
      insert into trangway.company_merge_row_log
        (batch_id, group_key, table_name, row_pk, column_name, old_value, new_value, action)
      values (v_batch_id, v_group_key, 'work_sites', r.id, 'company_id', r.company_id::text, v_keep_id::text, 'update');
      update trangway.work_sites set company_id = v_keep_id where id = r.id;
    end loop;
  end if;

  -- vendor_quotas
  if to_regclass('trangway.vendor_quotas') is not null then
    for r in
      select q.id, q.company_id from trangway.vendor_quotas q where q.company_id = any (v_drop_ids)
    loop
      insert into trangway.company_merge_row_log
        (batch_id, group_key, table_name, row_pk, column_name, old_value, new_value, action)
      values (v_batch_id, v_group_key, 'vendor_quotas', r.id, 'company_id', r.company_id::text, v_keep_id::text, 'update');
      update trangway.vendor_quotas set company_id = v_keep_id where id = r.id;
    end loop;
  end if;

  -- vendor_reconciliations
  if to_regclass('trangway.vendor_reconciliations') is not null then
    for r in
      select q.id, q.company_id from trangway.vendor_reconciliations q where q.company_id = any (v_drop_ids)
    loop
      insert into trangway.company_merge_row_log
        (batch_id, group_key, table_name, row_pk, column_name, old_value, new_value, action)
      values (v_batch_id, v_group_key, 'vendor_reconciliations', r.id, 'company_id', r.company_id::text, v_keep_id::text, 'update');
      update trangway.vendor_reconciliations set company_id = v_keep_id where id = r.id;
    end loop;
  end if;

  -- finance_transactions
  if to_regclass('trangway.finance_transactions') is not null then
    for r in
      select t.id, t.company_id from trangway.finance_transactions t where t.company_id = any (v_drop_ids)
    loop
      insert into trangway.company_merge_row_log
        (batch_id, group_key, table_name, row_pk, column_name, old_value, new_value, action)
      values (v_batch_id, v_group_key, 'finance_transactions', r.id, 'company_id', r.company_id::text, v_keep_id::text, 'update');
      update trangway.finance_transactions set company_id = v_keep_id where id = r.id;
    end loop;
  end if;

  -- cashbook company_name
  if to_regclass('trangway.cashbook_entries') is not null then
    for r in
      select e.id, e.company_name
        from trangway.cashbook_entries e
       where e.company_name is not null
         and e.company_name = any (v_drop_shorts)
    loop
      insert into trangway.company_merge_row_log
        (batch_id, group_key, table_name, row_pk, column_name, old_value, new_value, action)
      values (v_batch_id, v_group_key, 'cashbook_entries', r.id, 'company_name', r.company_name, v_keep_short, 'update');
      update trangway.cashbook_entries set company_name = v_keep_short where id = r.id;
    end loop;
  end if;

  -- commission_entries
  if to_regclass('trangway.commission_entries') is not null then
    for r in
      select e.id, e.company_name, e.period_code, to_jsonb(e) as row_json
        from trangway.commission_entries e
       where e.company_name = any (v_drop_shorts)
    loop
      if exists (
        select 1 from trangway.commission_entries x
         where x.period_code = r.period_code
           and lower(x.company_name) = lower(v_keep_short)
           and x.id <> r.id
      ) then
        insert into trangway.company_merge_row_log
          (batch_id, group_key, table_name, row_pk, column_name, old_value, new_value, action, deleted_row)
        values (v_batch_id, v_group_key, 'commission_entries', r.id, 'company_name', r.company_name, null, 'delete', r.row_json);
        delete from trangway.commission_entries where id = r.id;
      else
        insert into trangway.company_merge_row_log
          (batch_id, group_key, table_name, row_pk, column_name, old_value, new_value, action)
        values (v_batch_id, v_group_key, 'commission_entries', r.id, 'company_name', r.company_name, v_keep_short, 'update');
        update trangway.commission_entries set company_name = v_keep_short where id = r.id;
      end if;
    end loop;
  end if;

  foreach v_drop_id in array v_drop_ids
  loop
    select c.* into v_drop_row from trangway.companies c where c.id = v_drop_id;
    if not found then
      continue;
    end if;
    insert into trangway.company_merge_deleted_companies (batch_id, group_key, company_id, company_row)
    values (v_batch_id, v_group_key, v_drop_id, to_jsonb(v_drop_row));
    delete from trangway.companies where id = v_drop_id;
  end loop;

  raise notice 'DONE JAWA merge batch_id=% — rollback: select trangway.fn_rollback_company_merge(%);', v_batch_id, v_batch_id;
end $$;
