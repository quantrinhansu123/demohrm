-- Sổ chi hàng ngày. Chạy trong schema trangway.
create table if not exists trangway.cashbook_entries (
  id            bigint generated by default as identity primary key,
  entry_date    date not null,
  content       text not null,
  full_name     varchar(150),
  company_name  varchar(150),
  amount        numeric(14,2) not null,
  note          text,
  group_code    varchar(20) not null default 'other',
  group_name    varchar(100),
  created_at    timestamptz not null default now(),
  updated_at    timestamptz not null default now()
);

alter table trangway.cashbook_entries
  add column if not exists group_name varchar(100);

alter table trangway.cashbook_entries disable row level security;

grant select, insert, update, delete on trangway.cashbook_entries
  to anon, authenticated, service_role;
grant usage, select on sequence trangway.cashbook_entries_id_seq
  to anon, authenticated, service_role;

create index if not exists idx_cashbook_entry_date
  on trangway.cashbook_entries (entry_date);
