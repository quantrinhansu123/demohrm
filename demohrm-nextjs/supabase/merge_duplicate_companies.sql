-- =============================================================================
-- Gộp công ty trùng tên: giữ MAX(id), chuyển liên kết, xóa bản cũ.
-- Có bảng log + hàm rollback theo batch_id.
--
-- Cách dùng (Supabase SQL Editor):
--   1) Chạy toàn bộ file này (tạo log + chạy merge).
--   2) Xem batch:  select * from trangway.company_merge_batches order by id desc limit 5;
--   3) Rollback nếu cần:
--        select trangway.fn_rollback_company_merge(<batch_id>);
--
-- Quy tắc: ojitex ≠ Ojtex Thăng Long 3 (2 nhóm riêng).
-- Jawa "Khai quang" vs "Khai quang - Thời Vụ": chạy riêng merge_jawa_khai_quang.sql
--   (giữ "Jawa - KCN Khai quang", không dùng MAX(id) chung nhóm).
-- =============================================================================

create table if not exists trangway.company_merge_batches (
  id           bigint generated by default as identity primary key,
  note         text not null default 'merge_duplicate_companies',
  created_at   timestamptz not null default now(),
  rolled_back  boolean not null default false,
  rolled_back_at timestamptz
);

create table if not exists trangway.company_merge_group_log (
  id            bigint generated by default as identity primary key,
  batch_id      bigint not null references trangway.company_merge_batches(id) on delete cascade,
  group_key     text not null,
  keep_id       bigint not null,
  keep_snapshot jsonb not null,
  drop_ids      bigint[] not null,
  created_at    timestamptz not null default now()
);

-- Snapshot công ty bị xóa (để INSERT lại khi rollback).
create table if not exists trangway.company_merge_deleted_companies (
  id            bigint generated by default as identity primary key,
  batch_id      bigint not null references trangway.company_merge_batches(id) on delete cascade,
  group_key     text not null,
  company_id    bigint not null,
  company_row   jsonb not null,
  created_at    timestamptz not null default now()
);

-- Mọi thay đổi hàng để rollback theo thứ tự ngược.
create table if not exists trangway.company_merge_row_log (
  id            bigint generated by default as identity primary key,
  batch_id      bigint not null references trangway.company_merge_batches(id) on delete cascade,
  group_key     text not null,
  table_name    text not null,
  row_pk        bigint not null,
  column_name   text not null,
  old_value     text,
  new_value     text,
  action        text not null check (action in ('update', 'delete')),
  deleted_row   jsonb,
  created_at    timestamptz not null default now()
);

create index if not exists company_merge_row_log_batch_idx
  on trangway.company_merge_row_log (batch_id, id);

alter table trangway.company_merge_batches disable row level security;
alter table trangway.company_merge_group_log disable row level security;
alter table trangway.company_merge_deleted_companies disable row level security;
alter table trangway.company_merge_row_log disable row level security;

grant select, insert, update, delete on trangway.company_merge_batches to service_role;
grant select, insert, update, delete on trangway.company_merge_group_log to service_role;
grant select, insert, update, delete on trangway.company_merge_deleted_companies to service_role;
grant select, insert, update, delete on trangway.company_merge_row_log to service_role;

-- -----------------------------------------------------------------------------
-- Preview (chỉ đọc) — chạy riêng nếu muốn xem trước:
-- -----------------------------------------------------------------------------
-- with keys(group_key) as (
--   values
--     ('compal bt1'),
--     ('hrp - bình xuyên 2'),
--     ('jawa - kcn khai quang - thời vụ'),
--     ('minda'),
--     ('ojitex'),
--     ('ojtex thăng long 3'),
--     ('star'),
--     ('sunway'),
--     ('tal'),
--     ('token - thăng long 3')
-- )
-- select k.group_key, c.id, c.code, c.short_name, c.name,
--        (select count(*) from trangway.orders o where o.company_id = c.id) as orders_cnt,
--        (select count(*) from trangway.workers w where w.current_company_id = c.id) as workers_cnt
--   from keys k
--   join trangway.companies c
--     on lower(trim(c.short_name)) = k.group_key
--  order by k.group_key, c.id;

-- -----------------------------------------------------------------------------
-- Merge
-- -----------------------------------------------------------------------------
do $$
declare
  v_batch_id bigint;
  v_group_key text;
  v_keep_id bigint;
  v_keep_short text;
  v_keep_row jsonb;
  v_drop_ids bigint[];
  v_drop_id bigint;
  v_drop_row record;
  v_drop_shorts text[];
  r record;
  v_keys text[] := array[
    'compal bt1',
    'hrp - bình xuyên 2',
    'jawa - kcn khai quang - thời vụ',
    'minda',
    'ojitex',
    'ojtex thăng long 3',
    'star',
    'sunway',
    'tal',
    'token - thăng long 3'
  ];
begin
  insert into trangway.company_merge_batches (note)
  values ('merge_duplicate_companies ' || to_char(now(), 'YYYY-MM-DD HH24:MI:SS'))
  returning id into v_batch_id;

  raise notice 'company_merge batch_id=%', v_batch_id;

  foreach v_group_key in array v_keys
  loop
    select max(c.id)
      into v_keep_id
      from trangway.companies c
     where lower(trim(c.short_name)) = v_group_key;

    if v_keep_id is null then
      raise notice 'skip group "%" — không có công ty', v_group_key;
      continue;
    end if;

    select coalesce(array_agg(c.id order by c.id) filter (where c.id <> v_keep_id), '{}'::bigint[])
      into v_drop_ids
      from trangway.companies c
     where lower(trim(c.short_name)) = v_group_key;

    if coalesce(cardinality(v_drop_ids), 0) = 0 then
      raise notice 'skip group "%" — không trùng (chỉ 1 bản id=%)', v_group_key, v_keep_id;
      continue;
    end if;

    select to_jsonb(c), c.short_name
      into v_keep_row, v_keep_short
      from trangway.companies c
     where c.id = v_keep_id;

    select coalesce(array_agg(distinct c.short_name), '{}'::text[])
      into v_drop_shorts
      from trangway.companies c
     where c.id = any (v_drop_ids);

    insert into trangway.company_merge_group_log (batch_id, group_key, keep_id, keep_snapshot, drop_ids)
    values (v_batch_id, v_group_key, v_keep_id, v_keep_row, v_drop_ids);

    raise notice 'merge group "%" keep=% drop=%', v_group_key, v_keep_id, v_drop_ids;

    -- ---- orders.company_id ----
    for r in
      select o.id, o.company_id
        from trangway.orders o
       where o.company_id = any (v_drop_ids)
    loop
      insert into trangway.company_merge_row_log
        (batch_id, group_key, table_name, row_pk, column_name, old_value, new_value, action)
      values
        (v_batch_id, v_group_key, 'orders', r.id, 'company_id', r.company_id::text, v_keep_id::text, 'update');
      update trangway.orders set company_id = v_keep_id where id = r.id;
    end loop;

    -- ---- workers.current_company_id ----
    for r in
      select w.id, w.current_company_id
        from trangway.workers w
       where w.current_company_id = any (v_drop_ids)
    loop
      insert into trangway.company_merge_row_log
        (batch_id, group_key, table_name, row_pk, column_name, old_value, new_value, action)
      values
        (v_batch_id, v_group_key, 'workers', r.id, 'current_company_id', r.current_company_id::text, v_keep_id::text, 'update');
      update trangway.workers set current_company_id = v_keep_id where id = r.id;
    end loop;

    -- ---- work_sites.company_id ----
    if to_regclass('trangway.work_sites') is not null then
      for r in
        select s.id, s.company_id
          from trangway.work_sites s
         where s.company_id = any (v_drop_ids)
      loop
        insert into trangway.company_merge_row_log
          (batch_id, group_key, table_name, row_pk, column_name, old_value, new_value, action)
        values
          (v_batch_id, v_group_key, 'work_sites', r.id, 'company_id', r.company_id::text, v_keep_id::text, 'update');
        update trangway.work_sites set company_id = v_keep_id where id = r.id;
      end loop;
    end if;

    -- ---- vendor_quotas.company_id ----
    if to_regclass('trangway.vendor_quotas') is not null then
      for r in
        select q.id, q.company_id
          from trangway.vendor_quotas q
         where q.company_id = any (v_drop_ids)
      loop
        insert into trangway.company_merge_row_log
          (batch_id, group_key, table_name, row_pk, column_name, old_value, new_value, action)
        values
          (v_batch_id, v_group_key, 'vendor_quotas', r.id, 'company_id', r.company_id::text, v_keep_id::text, 'update');
        update trangway.vendor_quotas set company_id = v_keep_id where id = r.id;
      end loop;
    end if;

    -- ---- vendor_reconciliations.company_id ----
    if to_regclass('trangway.vendor_reconciliations') is not null then
      for r in
        select q.id, q.company_id
          from trangway.vendor_reconciliations q
         where q.company_id = any (v_drop_ids)
      loop
        insert into trangway.company_merge_row_log
          (batch_id, group_key, table_name, row_pk, column_name, old_value, new_value, action)
        values
          (v_batch_id, v_group_key, 'vendor_reconciliations', r.id, 'company_id', r.company_id::text, v_keep_id::text, 'update');
        update trangway.vendor_reconciliations set company_id = v_keep_id where id = r.id;
      end loop;
    end if;

    -- ---- finance_transactions.company_id ----
    if to_regclass('trangway.finance_transactions') is not null then
      for r in
        select t.id, t.company_id
          from trangway.finance_transactions t
         where t.company_id = any (v_drop_ids)
      loop
        insert into trangway.company_merge_row_log
          (batch_id, group_key, table_name, row_pk, column_name, old_value, new_value, action)
        values
          (v_batch_id, v_group_key, 'finance_transactions', r.id, 'company_id', r.company_id::text, v_keep_id::text, 'update');
        update trangway.finance_transactions set company_id = v_keep_id where id = r.id;
      end loop;
    end if;

    -- ---- cashbook_entries.company_name (chuỗi) ----
    if to_regclass('trangway.cashbook_entries') is not null then
      for r in
        select e.id, e.company_name
          from trangway.cashbook_entries e
         where e.company_name is not null
           and e.company_name = any (v_drop_shorts)
      loop
        insert into trangway.company_merge_row_log
          (batch_id, group_key, table_name, row_pk, column_name, old_value, new_value, action)
        values
          (v_batch_id, v_group_key, 'cashbook_entries', r.id, 'company_name', r.company_name, v_keep_short, 'update');
        update trangway.cashbook_entries set company_name = v_keep_short where id = r.id;
      end loop;
    end if;

    -- ---- commission_entries.company_name (unique period+name) ----
    if to_regclass('trangway.commission_entries') is not null then
      for r in
        select e.id, e.company_name, e.period_code, to_jsonb(e) as row_json
          from trangway.commission_entries e
         where e.company_name = any (v_drop_shorts)
      loop
        if exists (
          select 1
            from trangway.commission_entries x
           where x.period_code = r.period_code
             and lower(x.company_name) = lower(v_keep_short)
             and x.id <> r.id
        ) then
          -- Trùng period+tên keep → xóa dòng alias (đã có bản keep).
          insert into trangway.company_merge_row_log
            (batch_id, group_key, table_name, row_pk, column_name, old_value, new_value, action, deleted_row)
          values
            (v_batch_id, v_group_key, 'commission_entries', r.id, 'company_name', r.company_name, null, 'delete', r.row_json);
          delete from trangway.commission_entries where id = r.id;
        else
          insert into trangway.company_merge_row_log
            (batch_id, group_key, table_name, row_pk, column_name, old_value, new_value, action)
          values
            (v_batch_id, v_group_key, 'commission_entries', r.id, 'company_name', r.company_name, v_keep_short, 'update');
          update trangway.commission_entries set company_name = v_keep_short where id = r.id;
        end if;
      end loop;
    end if;

    -- ---- Xóa công ty trùng (sau khi đã chuyển FK) ----
    foreach v_drop_id in array v_drop_ids
    loop
      select c.* into v_drop_row from trangway.companies c where c.id = v_drop_id;
      if not found then
        continue;
      end if;

      insert into trangway.company_merge_deleted_companies (batch_id, group_key, company_id, company_row)
      values (v_batch_id, v_group_key, v_drop_id, to_jsonb(v_drop_row));

      delete from trangway.companies where id = v_drop_id;
    end loop;
  end loop;

  raise notice 'DONE company_merge batch_id=% — rollback: select trangway.fn_rollback_company_merge(%);', v_batch_id, v_batch_id;
end $$;

-- -----------------------------------------------------------------------------
-- Rollback theo batch_id
-- -----------------------------------------------------------------------------
create or replace function trangway.fn_rollback_company_merge(p_batch_id bigint)
returns json
language plpgsql
security definer
set search_path = trangway, public
as $$
declare
  v_batch trangway.company_merge_batches%rowtype;
  r record;
  v_restored int := 0;
  v_reverted int := 0;
begin
  select * into v_batch from trangway.company_merge_batches where id = p_batch_id;
  if not found then
    raise exception 'batch_not_found: %', p_batch_id;
  end if;
  if v_batch.rolled_back then
    raise exception 'batch_already_rolled_back: %', p_batch_id;
  end if;

  -- 1) Khôi phục công ty đã xóa (identity insert theo id cũ).
  for r in
    select *
      from trangway.company_merge_deleted_companies
     where batch_id = p_batch_id
     order by id
  loop
    if exists (select 1 from trangway.companies c where c.id = r.company_id) then
      raise notice 'company id=% already exists — skip restore', r.company_id;
      continue;
    end if;

    insert into trangway.companies (
      id, code, short_name, name, hotline, contact_name, contact_phone, bill_rate_per_day, status
    )
    overriding system value
    values (
      r.company_id,
      r.company_row->>'code',
      r.company_row->>'short_name',
      r.company_row->>'name',
      r.company_row->>'hotline',
      r.company_row->>'contact_name',
      r.company_row->>'contact_phone',
      nullif(r.company_row->>'bill_rate_per_day', '')::numeric,
      coalesce(r.company_row->>'status', 'active')
    );
    v_restored := v_restored + 1;
  end loop;

  -- Đồng bộ sequence/identity sau khi restore id cũ.
  perform setval(
    pg_get_serial_sequence('trangway.companies', 'id'),
    greatest(
      (select coalesce(max(id), 1) from trangway.companies),
      1
    ),
    true
  );

  -- 2) Hoàn tác thay đổi hàng (ngược thứ tự log).
  for r in
    select *
      from trangway.company_merge_row_log
     where batch_id = p_batch_id
     order by id desc
  loop
    if r.action = 'update' then
      if r.table_name = 'orders' and r.column_name = 'company_id' then
        update trangway.orders set company_id = r.old_value::bigint where id = r.row_pk;
      elsif r.table_name = 'workers' and r.column_name = 'current_company_id' then
        update trangway.workers set current_company_id = r.old_value::bigint where id = r.row_pk;
      elsif r.table_name = 'work_sites' and r.column_name = 'company_id' then
        update trangway.work_sites set company_id = r.old_value::bigint where id = r.row_pk;
      elsif r.table_name = 'vendor_quotas' and r.column_name = 'company_id' then
        update trangway.vendor_quotas set company_id = r.old_value::bigint where id = r.row_pk;
      elsif r.table_name = 'vendor_reconciliations' and r.column_name = 'company_id' then
        update trangway.vendor_reconciliations set company_id = r.old_value::bigint where id = r.row_pk;
      elsif r.table_name = 'finance_transactions' and r.column_name = 'company_id' then
        update trangway.finance_transactions set company_id = r.old_value::bigint where id = r.row_pk;
      elsif r.table_name = 'cashbook_entries' and r.column_name = 'company_name' then
        update trangway.cashbook_entries set company_name = r.old_value where id = r.row_pk;
      elsif r.table_name = 'commission_entries' and r.column_name = 'company_name' then
        update trangway.commission_entries set company_name = r.old_value where id = r.row_pk;
      end if;
      v_reverted := v_reverted + 1;
    elsif r.action = 'delete' and r.table_name = 'commission_entries' and r.deleted_row is not null then
      if not exists (select 1 from trangway.commission_entries e where e.id = r.row_pk) then
        insert into trangway.commission_entries (
          id, company_name, unit_price, period_code, created_by, created_at, updated_at
        )
        overriding system value
        values (
          r.row_pk,
          r.deleted_row->>'company_name',
          (r.deleted_row->>'unit_price')::numeric,
          r.deleted_row->>'period_code',
          nullif(r.deleted_row->>'created_by', '')::bigint,
          coalesce((r.deleted_row->>'created_at')::timestamptz, now()),
          coalesce((r.deleted_row->>'updated_at')::timestamptz, now())
        );
      end if;
      v_reverted := v_reverted + 1;
    end if;
  end loop;

  update trangway.company_merge_batches
     set rolled_back = true,
         rolled_back_at = now()
   where id = p_batch_id;

  return json_build_object(
    'batch_id', p_batch_id,
    'companies_restored', v_restored,
    'rows_reverted', v_reverted,
    'ok', true
  );
end;
$$;

grant execute on function trangway.fn_rollback_company_merge(bigint) to service_role;

